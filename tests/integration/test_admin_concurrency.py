def test_concurrent_initial_platform_bootstraps_allow_exactly_one(
    integration_engine, shared_schema
):
    from editingtab_core.platform import services as platform

    with (
        scoped_connection(integration_engine, shared_schema) as connection,
        Session(connection) as session,
    ):
        for name in ("first", "second"):
            identity.create_user(session, email=f"{name}@example.test", display_name=name)
    pids = Queue()

    def attempt(name):
        with scoped_connection(integration_engine, shared_schema) as connection:
            pid = connection.scalar(text("SELECT pg_backend_pid()"))
            connection.commit()
            pids.put(pid)
            with Session(connection) as session:
                try:
                    platform.bootstrap_initial(session, email=f"{name}@example.test")
                    return "granted"
                except platform.BootstrapClosed:
                    return "closed"

    with scoped_connection(integration_engine, shared_schema) as gate:
        gate.execute(text("SELECT id FROM core_platform_bootstrap WHERE id = 1 FOR UPDATE"))
        with ThreadPoolExecutor(max_workers=2) as workers:
            futures = [workers.submit(attempt, name) for name in ("first", "second")]
            try:
                worker_pids = [pids.get(timeout=3), pids.get(timeout=3)]
                deadline = time.monotonic() + 2
                with integration_engine.connect() as observer:
                    while True:
                        waiting = [
                            observer.scalar(
                                text("SELECT cardinality(pg_blocking_pids(:pid)) > 0"), {"pid": pid}
                            )
                            for pid in worker_pids
                        ]
                        if all(waiting):
                            break
                        assert time.monotonic() < deadline, (
                            "Bootstrap workers did not reach concurrent locks"
                        )
                        time.sleep(0.01)
            finally:
                gate.rollback()
            assert sorted(f.result(timeout=5) for f in futures) == ["closed", "granted"]
    with scoped_connection(integration_engine, shared_schema) as connection:
        assert connection.scalar(text("SELECT count(*) FROM core_platform_admin_grants")) == 1
        assert (
            connection.scalar(
                text(
                    "SELECT count(*) FROM core_platform_audit "
                    "WHERE action = 'operator.bootstrap' AND actor_id IS NULL"
                )
            )
            == 1
        )
        assert (
            connection.scalar(
                text("SELECT completed_at IS NOT NULL FROM core_platform_bootstrap WHERE id = 1")
            )
            is True
        )


def test_concurrent_manager_scope_replacement_and_revocation_remain_consistent(
    integration_engine, shared_schema
):
    with (
        scoped_connection(integration_engine, shared_schema) as connection,
        Session(connection) as session,
    ):
        operator = identity.create_user(
            session, email="manager-operator@example.test", display_name="Operator"
        )
        manager = identity.create_user(
            session, email="concurrent-manager@example.test", display_name="Manager"
        )
        platform_services.bootstrap_initial(session, email="manager-operator@example.test")
        organization = identity.create_organization(
            session, name="Concurrent managers", slug="concurrent-managers"
        )
        membership = identity.add_membership(session, organization_id=organization, user_id=manager)
        with session.begin():
            operations = Role(
                organization_id=organization,
                name="Concurrent role operations",
                normalized_name="concurrent role operations",
            )
            session.add(operations)
            session.flush()
            session.add_all(
                [
                    *(
                        RolePermission(
                            organization_id=organization,
                            role_id=operations.id,
                            code=code,
                            can_grant=False,
                        )
                        for code in ADMINISTRATOR_PERMISSIONS
                    ),
                    MembershipRole(
                        organization_id=organization,
                        membership_id=membership,
                        role_id=operations.id,
                    ),
                    ModuleEntitlement(
                        organization_id=organization,
                        module_code="booking",
                        enabled=True,
                    ),
                ]
            )
        manager_lifecycle.designate(
            session,
            actor_id=operator,
            organization_id=organization,
            membership_id=membership,
            scopes=["booking.inventory.read"],
        )

    pids = Queue()

    def replace_scopes():
        with scoped_connection(integration_engine, shared_schema) as connection:
            pids.put(connection.scalar(text("SELECT pg_backend_pid()")))
            connection.commit()
            with Session(connection) as session:
                manager_lifecycle.designate(
                    session,
                    actor_id=operator,
                    organization_id=organization,
                    membership_id=membership,
                    scopes=["booking.inventory.manage"],
                )

    def revoke():
        with scoped_connection(integration_engine, shared_schema) as connection:
            pids.put(connection.scalar(text("SELECT pg_backend_pid()")))
            connection.commit()
            with Session(connection) as session:
                manager_lifecycle.revoke(
                    session,
                    actor_id=operator,
                    organization_id=organization,
                    membership_id=membership,
                )

    with scoped_connection(integration_engine, shared_schema) as gate:
        gate.execute(
            text("SELECT id FROM core_organizations WHERE id = :id FOR UPDATE"),
            {"id": organization},
        )
        with ThreadPoolExecutor(max_workers=2) as workers:
            futures = [workers.submit(replace_scopes), workers.submit(revoke)]
            try:
                worker_pids = [pids.get(timeout=3), pids.get(timeout=3)]
                deadline = time.monotonic() + 2
                with integration_engine.connect() as observer:
                    while True:
                        waiting = [
                            observer.scalar(
                                text("SELECT cardinality(pg_blocking_pids(:pid)) > 0"),
                                {"pid": pid},
                            )
                            for pid in worker_pids
                        ]
                        if all(waiting):
                            break
                        assert time.monotonic() < deadline, (
                            "Manager workers did not reach the organization lock"
                        )
                        time.sleep(0.01)
            finally:
                gate.rollback()
            for future in futures:
                future.result(timeout=5)

    with (
        scoped_connection(integration_engine, shared_schema) as connection,
        Session(connection) as session,
    ):
        rows = manager_lifecycle.list_managers(
            session, actor_id=operator, organization_id=organization
        )
        assert len(rows) == 1
        row = rows[0]
        assignment = session.get(
            MembershipRole,
            (organization, membership, row["role_id"]),
        )
        authority = repository.effective_grant_only_permission_management_authority(
            session, organization, manager
        )
        if row["state"] == "active":
            assert row["scopes"] == ["booking.inventory.manage"]
            assert assignment is not None
            assert authority == {"booking.inventory.manage"}
        else:
            assert row["state"] == "revoked"
            assert assignment is None
            assert authority == frozenset()


def test_concurrent_invitation_acceptance_creates_one_account_and_membership(
    integration_engine, integration_settings, shared_schema
):
    passwords = Passwords()
    with (
        scoped_connection(integration_engine, shared_schema) as connection,
        Session(connection) as session,
    ):
        owner = provision_user(
            session,
            settings=integration_settings,
            passwords=passwords,
            email="invite-owner@example.test",
            display_name="Invite Owner",
            password="test-only owner password long enough",
        )
        org = bootstrap(
            session,
            settings=integration_settings,
            email="invite-owner@example.test",
            slug="concurrent-invite",
            name="Concurrent invite",
        )
        invitation = auth_services.create_invitation(
            session,
            settings=integration_settings,
            organization_id=org,
            actor_id=owner,
            email="concurrent-employee@example.test",
        )
    pids = Queue()

    def accept():
        with scoped_connection(integration_engine, shared_schema) as connection:
            pid = connection.scalar(text("SELECT pg_backend_pid()"))
            connection.commit()
            pids.put(pid)
            with Session(connection) as session:
                try:
                    auth_services.accept_invitation(
                        session,
                        passwords=passwords,
                        token=invitation["token"],
                        email="concurrent-employee@example.test",
                        display_name="Concurrent Employee",
                        password="test-only employee password long enough",
                    )
                    return "accepted"
                except AuthenticationError:
                    return "rejected"

    with scoped_connection(integration_engine, shared_schema) as gate:
        gate.execute(
            text("SELECT id FROM core_organization_invitations WHERE id = :id FOR UPDATE"),
            {"id": invitation["id"]},
        )
        with ThreadPoolExecutor(max_workers=2) as workers:
            futures = [workers.submit(accept) for _ in range(2)]
            try:
                worker_pids = [pids.get(timeout=3), pids.get(timeout=3)]
                deadline = time.monotonic() + 2
                with integration_engine.connect() as observer:
                    while True:
                        waiting = [
                            observer.scalar(
                                text("SELECT cardinality(pg_blocking_pids(:pid)) > 0"),
                                {"pid": pid},
                            )
                            for pid in worker_pids
                        ]
                        if all(waiting):
                            break
                        assert time.monotonic() < deadline, (
                            "Invitation workers did not reach concurrent lock"
                        )
            finally:
                gate.rollback()
            assert sorted(future.result(timeout=10) for future in futures) == [
                "accepted",
                "rejected",
            ]
    with scoped_connection(integration_engine, shared_schema) as connection:
        assert (
            connection.scalar(
                text("SELECT count(*) FROM core_users WHERE normalized_email = :email"),
                {"email": "concurrent-employee@example.test"},
            )
            == 1
        )
        assert (
            connection.scalar(
                text(
                    "SELECT count(*) FROM core_memberships m JOIN core_users u ON u.id = m.user_id "
                    "WHERE m.organization_id = :org AND u.normalized_email = :email"
                ),
                {"org": org, "email": "concurrent-employee@example.test"},
            )
            == 1
        )
